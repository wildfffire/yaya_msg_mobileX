/**
 * 一段文本里所有认识的短码替换成 emoji；不认识的原样保留。
 *
 * 支持半角 `[]` 与全角 `［］`（用户输入法切到全角时很常见）。
 * 括号内长度限定 1~8：既覆盖最长码（如 `[左哼哼]`），又避免把
 * `[一大段中括号里的话]` 当表情去查表。
 */
export function replaceEmojiText(text: string): string {
  if (!text) return text;
  return String(text).replace(/[\[［]([^\[\]［］]{1,8})[\]］]/g, (match, inner: string) => {
    const key = `[${String(inner).trim()}]`;
    return EMOJI_MAP[key] || match;
  });
}
